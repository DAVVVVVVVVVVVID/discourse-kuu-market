# frozen_string_literal: true

RSpec.describe DiscourseKuuMarket::FormSubmission do
  fab!(:user)
  fab!(:category)

  let(:title) { "【赠送】伞" }

  before do
    SiteSetting.kuu_market_enabled = true
    SiteSetting.min_topic_title_length = 15
    described_class.submit(title) { Fabricate(:topic, title:, category:) }
  end

  def build_topic(topic_title = title)
    Topic.new(title: topic_title, user:, category:)
  end

  it "keeps core's title rules for other titles" do
    described_class.submit(title) do
      topic = build_topic("【赠送】锅")

      expect(topic).not_to be_valid
      expect(topic.errors.of_kind?(:title, :too_short)).to eq(true)
    end
  end

  it "forgives a short, low-quality or duplicate title generated by the plugin" do
    described_class.submit(title) { expect(build_topic).to be_valid }
  end

  it "keeps the rules outside the block" do
    described_class.submit(title) {}

    topic = build_topic
    expect(topic).not_to be_valid
    expect(topic.errors.of_kind?(:base, :topic_title_already_used)).to eq(true)
  end

  it "still applies watched words to a generated title" do
    Fabricate(:watched_word, word: "伞", action: WatchedWord.actions[:block])

    described_class.submit(title) { expect(build_topic).not_to be_valid }
  end

  it "does nothing while the plugin is disabled" do
    SiteSetting.kuu_market_enabled = false

    described_class.submit(title) { expect(build_topic).not_to be_valid }
  end
end
